// Writes THIRD_PARTY_NOTICES.md: every package that ships inside the RealmNest OS exe, with its
// licence and the licence text it carries (MIT, BSD and OFL require the notice to travel with it).
//   node tools/third-party-notices.mjs
// Offline: npm packages come from package-lock.json + node_modules (dev-only ones are left out);
// Rust crates from `cargo metadata` for the Windows target + the local cargo registry sources.

import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const LICENSE_FILE = /^(licen[cs]e|copying|notice|ofl)([-._].*)?(\.(md|txt))?$/i;

function licenceTexts(dir) {
  if (!dir || !existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => ({ file: f, text: readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim() }));
}

// ── npm: what the app bundles (dependencies, not devDependencies) ──
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
const npm = Object.entries(lock.packages)
  .filter(([path, p]) => path && !p.dev && path.startsWith('node_modules/'))
  .map(([path, p]) => {
    const name = path.replace(/^.*node_modules\//, '');
    return { name, version: p.version, license: p.license ?? 'see text', texts: licenceTexts(join(root, path)) };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

// ── Rust: crates built for Windows ──
const meta = JSON.parse(
  execFileSync('cargo', ['metadata', '--offline', '--locked', '--format-version', '1', '--filter-platform', 'x86_64-pc-windows-msvc', '--manifest-path', join(root, 'src-tauri', 'Cargo.toml')], { encoding: 'utf8', maxBuffer: 256 << 20 }),
);
const used = new Set();
const byId = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const walk = (id) => {
  if (used.has(id)) return;
  used.add(id);
  for (const d of byId.get(id)?.deps ?? []) if (d.dep_kinds.some((k) => k.kind === null)) walk(d.pkg);
};
walk(meta.resolve.root);
const crates = meta.packages
  .filter((p) => used.has(p.id) && p.source)
  .map((p) => ({ name: p.name, version: p.version, license: p.license ?? (p.license_file ? 'see text' : 'unknown'), texts: licenceTexts(p.manifest_path.replace(/[\\/]Cargo\.toml$/, '')) }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

// ── the file ──
const section = (title, list) => [
  `## ${title} (${list.length})`,
  '',
  '| package | version | licence |',
  '| --- | --- | --- |',
  ...list.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
  '',
  ...list.flatMap((p) => (p.texts.length ? [`### ${p.name} ${p.version}`, '', ...p.texts.flatMap((t) => [`\`${t.file}\``, '', '```text', t.text, '```', ''])] : [])),
];
const missing = [...npm, ...crates].filter((p) => !p.texts.length).map((p) => `${p.name} ${p.version} (${p.license})`);
writeFileSync(
  join(root, 'THIRD_PARTY_NOTICES.md'),
  [
    '# Third-party notices',
    '',
    'RealmNest OS is licensed under the GNU AGPL v3 or later (see LICENSE). It ships the following third-party components under their own licences, reproduced below as the packages provide them. Generated by `node tools/third-party-notices.mjs`.',
    '',
    'Fonts: Inter, Fraunces and JetBrains Mono are bundled from the @fontsource packages under the SIL Open Font License 1.1 (texts below). Icons: Lucide (ISC). WebView2 is part of Windows and is not redistributed with the exe. The Windows installer is built with NSIS (zlib licence) from the installer template of tauri-bundler (Apache-2.0 OR MIT, the Tauri licence texts below), adapted in src-tauri/installer/installer.nsi.',
    '',
    ...section('npm packages bundled in the app', npm),
    ...section('Rust crates compiled into the exe (Windows)', crates),
    ...(missing.length ? ['## Packages without a licence file in their sources', '', 'Their licence is the SPDX expression in the tables above.', '', ...missing.map((m) => `- ${m}`), ''] : []),
  ].join('\n'),
);
console.log(`THIRD_PARTY_NOTICES.md: ${npm.length} npm packages, ${crates.length} crates, ${missing.length} without a licence file`);
