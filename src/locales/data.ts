/** the leading word of an activity built by the simulation (src/engine/worldSim.ts): "Relaxing · Lounge sofa" */
const ACTIVITY_HEAD_IT: Record<string, string> = {
  Research: 'Ricerca',
  Waiting: 'In attesa',
  Paused: 'Sospeso',
  'On break': 'In pausa',
  Huddle: 'Riunione',
  'Getting a coffee': 'Prende un caffè',
  Relaxing: 'Si rilassa',
};

/** activities with a name or a title inside: "Working on “Fix flaky test”", "Chatting with Hana" */
const ACTIVITY_IT: [RegExp, (m: RegExpExecArray, tr: (s: string) => string) => string][] = [
  [/^Working on “(.+)”$/, (m, tr) => `Al lavoro su “${tr(m[1])}”`],
  [/^“(.+)”$/, (m, tr) => `“${tr(m[1])}”`],
  [/^Chatting with (.+)$/, (m) => `Chiacchiera con ${m[1]}`],
  [/^Handing off to (.+)$/, (m) => `Passa il lavoro a ${m[1]}`],
  [/^Delegating to (.+)$/, (m) => `Delega a ${m[1]}`],
  [/^Looking at (.+)$/, (m, tr) => `Guarda: ${tr(m[1])}`],
  [/^Waiting for (.+)$/, (m) => `Aspetta ${m[1]}`],
  [/^Error: (.+)$/, (m) => `Errore: ${m[1]}`],
];

function toItalian(text: string): string {
  const exact = DATA_IT[text] ?? ACTIVITY_HEAD_IT[text];
  if (exact) return exact;
  // "<head> · <rest>": each part on its own (a station, a task, a free message stays as it is)
  const dot = text.indexOf(' · ');
  if (dot > 0) return `${toItalian(text.slice(0, dot))} · ${toItalian(text.slice(dot + 3))}`;
  for (const [re, say] of ACTIVITY_IT) {
    const m = re.exec(text);
    if (m) return say(m, toItalian);
  }
  return text;
}

/** a data text in the user's language: the Italian when there is one, else the text as it is */
export function dataText(lang: 'it' | 'en', text: string | undefined): string {
  if (!text) return text ?? '';
  return lang === 'it' ? toItalian(text) : text;
}
