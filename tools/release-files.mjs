// The public source set of RealmNest OS: what goes into the GitHub repository and the release
// source tree. Everything else in the development folder (art sources, renders, promo videos,
// build outputs, caches, local tool config) stays out.
//   node tools/release-files.mjs            → prints the list (one path per line)
//   node tools/release-files.mjs <dest>     → copies the set into <dest> (which must not exist)

import { copyFileSync, existsSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');

/** top-level files that belong to the repository */
const ROOT_FILES = ['README.md', 'LICENSE', 'SECURITY.md', 'CONTRIBUTING.md', 'ASSETS.md', 'CHANGELOG.md', 'THIRD_PARTY_NOTICES.md', 'package.json', 'package-lock.json', 'tsconfig.json', 'vite.config.ts', 'index.html', 'charpipe.html', '.gitignore', '.gitattributes'];

/** folders taken whole, minus the exclusions below */
const DIRS = ['src', 'public', 'src-tauri', 'tools', 'examples', '.github', 'docs'];

/** never copied, wherever they are */
const EXCLUDE = [
  /^src-tauri\/target\//,
  /^src-tauri\/gen\//, // regenerated by every Tauri build
  /(^|\/)node_modules\//,
  /(^|\/)dist\//,
  /\.tsbuildinfo$/,
  /(^|\/)\.DS_Store$/,
  /\.log$/,
  /(^|\/)__pycache__\//,
  // docs: the Markdown docs and the provider notes; the art working folders (bakes, renders,
  // character sheets), acceptance archives and screenshots with personal data stay in development
  /^docs\/(archive|screens|farm-bake|worlds-bake|characters|farm-2x|worlds-2x|office-bake|farm-slice|notte|charpipe)\//,
  // release outputs made by the packaging scripts
  /^release-(staging|artifacts)\//,
];

function walk(dir, out) {
  for (const name of readdirSync(join(root, dir))) {
    const rel = `${dir}/${name}`;
    if (EXCLUDE.some((r) => r.test(rel + (statSync(join(root, rel)).isDirectory() ? '/' : '')))) continue;
    if (statSync(join(root, rel)).isDirectory()) walk(rel, out);
    else out.push(rel);
  }
  return out;
}

/** the character pipeline's small data files that tools/charpipe and its tests read (art/ itself, 2 GB of sources and renders, stays out) */
const ART_DATA = [/^art\/charpipe\/README\.md$/, /^art\/charpipe\/(rig|animations)\/[^/]+\.json$/, /^art\/charpipe\/characters\/[^/]+\/(character|[^/]+\.spec)\.json$/, /^art\/charpipe\/characters\/alex\/source\/alex_se\.png$/];

function artData(out) {
  const dirs = ['art/charpipe', 'art/charpipe/rig', 'art/charpipe/animations', ...(existsSync(join(root, 'art/charpipe/characters')) ? readdirSync(join(root, 'art/charpipe/characters')).flatMap((c) => [`art/charpipe/characters/${c}`, `art/charpipe/characters/${c}/source`]) : [])];
  for (const d of dirs) {
    if (!existsSync(join(root, d)) || !statSync(join(root, d)).isDirectory()) continue;
    for (const name of readdirSync(join(root, d))) if (ART_DATA.some((r) => r.test(`${d}/${name}`))) out.push(`${d}/${name}`);
  }
  return out;
}

export function releaseFiles() {
  const files = ROOT_FILES.filter((f) => existsSync(join(root, f)));
  for (const d of DIRS) if (existsSync(join(root, d))) walk(d, files);
  artData(files);
  return files.sort();
}

const dest = process.argv[2];
const files = releaseFiles();
if (!dest) {
  console.log(files.join('\n'));
} else {
  if (existsSync(dest)) throw new Error(`${dest} already exists: choose a new folder`);
  for (const f of files) {
    const to = join(dest, ...f.split('/'));
    mkdirSync(dirname(to), { recursive: true });
    copyFileSync(join(root, ...f.split('/')), to);
  }
  console.log(`copied ${files.length} files to ${relative(process.cwd(), dest) || dest}`.split(sep).join('/'));
}
