// Character pipeline prototype, step 2: drive EffectCraft headless.
//
// buildTemplate()  writes a JSX script from the rig + animations + one outfit's parts and runs
//                  `effectcraft-cli script` to create the template project (.ecproj):
//                    nestra-character-template/{rig, body, clothing, hair, accessories, animations}
//                  every animation is a comp of joint nulls (keyed, Hold) carrying Draft-quality art layers.
// makeVariant()    copies the template through `effectcraft-cli run file.replaceFootage …` (the same
//                  JSON engine commands MCP exposes) to swap the outfit and toggle accessories.
// render()         `effectcraft-cli render --format png --channels rgba` per animation comp.
import { execFileSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { decompose, stepOf } from './rigmath';
import { effectcraftCli, type AnimationSpec, type CharacterSpec, type Rig } from './spec';

const fwd = (p: string) => p.replace(/\\/g, '/');

function cli(args: string[], what: string): string {
  try {
    return execFileSync(effectcraftCli(), args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 300_000 });
  } catch (e) {
    const err = e as { stderr?: string; stdout?: string; message: string };
    throw new Error(`effectcraft-cli ${what} failed: ${err.stderr || err.stdout || err.message}`);
  }
}

export function effectcraftVersion(): string {
  return cli(['--version'], '--version').trim();
}

export interface TemplateInput {
  rig: Rig;
  ch: CharacterSpec;
  anims: AnimationSpec[];
  /** 1 = art pixels; 8 = parts enlarged with Scale2x ×3, sampled back after rendering (RotSprite) */
  k: number;
  /** art layer → png (a joint id for cut-out characters, a layer id for layered ones) */
  parts: Record<string, string>;
  accessories: Record<string, string>;
  out: string;
}

/** The art layers back to front, each riding on a joint. */
export function artLayers(rig: Rig, ch: CharacterSpec): { name: string; joint: string; folder: string }[] {
  if (ch.layers) return ch.layers.map((l) => ({ name: l.id, joint: l.joint, folder: l.folder ?? 'body' }));
  return rig.drawOrder.map((j) => ({ name: j, joint: j, folder: 'body' }));
}

/**
 * The JSX that builds the template project. All numbers are precomputed here; the script only
 * places them. Per animation comp: one null per rig joint (`j_<joint>`, parented as the rig says,
 * carrying every key), an extra `g_<joint>` null above a stepping limb (the skew), and the art
 * layers, back to front, each parented to its joint's null at identity.
 */
export function templateJsx(t: TemplateInput): string {
  const { rig, ch, k } = t;
  const data = {
    k,
    w: (ch.frame ?? rig.frame).w * k,
    h: (ch.frame ?? rig.frame).h * k,
    joints: rig.joints,
    layers: artLayers(rig, ch).map((l) => ({ ...l, path: fwd(t.parts[l.name]) })),
    pivots: Object.fromEntries(Object.entries(ch.pivots).map(([j, [x, y]]) => [j, [x * k, y * k]])),
    accessories: Object.entries(ch.accessories).map(([id, a]) => ({ id, joint: a.joint, path: fwd(t.accessories[id]) })),
    anims: t.anims.map((a) => ({
      id: a.id,
      frames: a.frames,
      fps: a.fps,
      drawOrder: a.drawOrder ?? null,
      tracks: a.tracks,
      // step tracks as a null (rotation r1, scale sx/sy) above the limb (extra rotation r2), per frame
      ground: Object.fromEntries(
        Object.keys(a.tracks)
          .filter((j) => a.tracks[j].step)
          .map((j) => [j, Array.from({ length: a.frames }, (_, f) => decompose(stepOf(rig, ch, a, j, f)!))]),
      ),
    })),
    out: fwd(t.out),
  };
  return `// generated by tools/charpipe/effectcraft.ts — do not edit; edit art/charpipe/*.json instead
var D = ${JSON.stringify(data)};
function folder(name, parent) { var f = app.project.items.addFolder(name); if (parent) f.parentFolder = parent; return f; }
var top = folder("nestra-character-template");
var F = { rig: folder("rig", top), body: folder("body", top), clothing: folder("clothing", top), hair: folder("hair", top), accessories: folder("accessories", top), animations: folder("animations", top) };
function load(path, name, fld) {
  var io = new ImportOptions(new File(path)); io.sequence = false;
  var it = app.project.importFile(io); it.name = name; it.parentFolder = fld; return it;
}
var items = {};
for (var i = 0; i < D.layers.length; i++) items[D.layers[i].name] = load(D.layers[i].path, D.layers[i].name, F[D.layers[i].folder] || F.body);
var accItems = {};
for (var i = 0; i < D.accessories.length; i++) accItems[D.accessories[i].id] = load(D.accessories[i].path, D.accessories[i].id, F.accessories);

function tr(l) { return l.property("ADBE Transform Group"); }
function place(l, p) { tr(l).property("ADBE Anchor Point").setValue(p); tr(l).property("ADBE Position").setValue(p); }
function hold(p) { for (var n = 1; n <= p.numKeys; n++) p.setInterpolationTypeAtKey(n, KeyframeInterpolationType.HOLD, KeyframeInterpolationType.HOLD); }
function art(comp, item, name, joint, J) { var l = comp.layers.add(item); l.name = name; l.quality = LayerQuality.DRAFT; l.parent = J["j_" + joint]; place(l, [0, 0]); return l; }

// the rest pose lives in rig/ for reference: one frame, no keys
var all = [{ id: "rest", frames: 1, fps: 8, drawOrder: null, tracks: {}, ground: {} }].concat(D.anims);
for (var a = 0; a < all.length; a++) {
  var A = all[a];
  var comp = app.project.items.addComp(A.id, D.w, D.h, 1, A.frames / A.fps, A.fps);
  comp.parentFolder = A.id === "rest" ? F.rig : F.animations;
  // the skeleton: a null per joint at its pivot, a ground null above each stepping limb
  var J = {};
  for (var i = D.joints.length - 1; i >= 0; i--) { var n = comp.layers.addNull(); n.name = "j_" + D.joints[i].id; J[n.name] = n; }
  for (var j in A.ground) { var g = comp.layers.addNull(); g.name = "g_" + j; J[g.name] = g; }
  for (var i = 0; i < D.joints.length; i++) {
    var id = D.joints[i].id, par = D.joints[i].parent;
    if (A.ground[id]) { J["g_" + id].parent = J["j_" + par]; J["j_" + id].parent = J["g_" + id]; }
    else if (par) J["j_" + id].parent = J["j_" + par];
  }
  for (var j in J) place(J[j], D.pivots[j.substring(2)]);
  // the art, back to front (an animation may reorder it by joint)
  var order = D.layers.slice();
  if (A.drawOrder) order.sort(function (x, y) { return A.drawOrder.indexOf(x.joint) - A.drawOrder.indexOf(y.joint); });
  for (var i = 0; i < order.length; i++) art(comp, items[order[i].name], order[i].name, order[i].joint, J);
  for (var i = 0; i < D.accessories.length; i++) { var ac = D.accessories[i]; art(comp, accItems[ac.id], "acc_" + ac.id, ac.joint, J).enabled = false; }
  // the keys, all on joint nulls
  for (var j in A.tracks) {
    var T = A.tracks[j], l = J["j_" + j], piv = D.pivots[j];
    if (!l) throw new Error("animation " + A.id + ": no joint " + j);
    var G = A.ground[j];
    if (G) {
      var gn = J["g_" + j], gr = tr(gn).property("ADBE Rotate Z"), gs = tr(gn).property("ADBE Scale");
      for (var f = 0; f < A.frames; f++) { gr.setValueAtTime(f / A.fps, G[f].r1); gs.setValueAtTime(f / A.fps, [G[f].sx, G[f].sy]); }
      hold(gr); hold(gs);
    }
    if (T.rot || G) { var p = tr(l).property("ADBE Rotate Z"); for (var f = 0; f < A.frames; f++) p.setValueAtTime(f / A.fps, ((T.rot && T.rot[f]) || 0) + (G ? G[f].r2 : 0)); hold(p); }
    if (T.dx || T.dy) {
      var p = tr(l).property("ADBE Position");
      for (var f = 0; f < A.frames; f++) p.setValueAtTime(f / A.fps, [piv[0] + ((T.dx && T.dx[f]) || 0) * D.k, piv[1] + ((T.dy && T.dy[f]) || 0) * D.k]);
      hold(p);
    }
  }
}
app.project.save(new File(D.out));
writeLn("saved " + D.out);
`;
}

export function buildTemplate(t: TemplateInput, scriptPath: string) {
  mkdirSync(dirname(scriptPath), { recursive: true });
  writeFileSync(scriptPath, templateJsx(t));
  rmSync(t.out, { force: true });
  return cli(['--empty', 'script', scriptPath], 'script').trim();
}

/** The template with another outfit's parts and the given accessories switched on, saved as `out`. */
export function makeVariant(template: string, out: string, parts: Record<string, string> | null, anims: string[], accessories: string[]) {
  const steps: string[] = [];
  // replaceFootage's `item` takes an id but not a name (0.8.0: "select footage"), so select by name first
  if (parts) for (const [item, path] of Object.entries(parts)) steps.push('project.select', JSON.stringify({ items: [item] }), 'file.replaceFootage', JSON.stringify({ path, sequence: false }));
  if (accessories.length)
    for (const comp of anims) {
      steps.push('comp.open', JSON.stringify({ comp }));
      steps.push('layer.setSwitch', JSON.stringify({ layers: accessories.map((a) => `acc_${a}`), switch: 'video', value: true }));
    }
  rmSync(out, { force: true });
  if (!steps.length) return cli(['--project', template, 'run', 'comp.open', JSON.stringify({ comp: anims[0] }), '--save-as', out], 'run');
  return cli(['--project', template, 'run', ...steps, '--save-as', out], 'run');
}

/** PNG sequence with alpha: <dir>/raw_000.png … */
export function render(project: string, comp: string, dir: string) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  return cli(['--project', project, 'render', '--comp', comp, '--out', join(dir, 'raw_[###].png'), '--format', 'png', '--channels', 'rgba', '--quality', 'draft'], `render ${comp}`).trim();
}
